package curs.repository.db;

import curs.domain.Utilizator;
import curs.domain.validators.Validator;
import curs.repository.Repository;
import curs.repository.RepositoryException;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Database repository for users; every operation is a query on the
 * table users(id, first_name, last_name). Keeps nothing in memory.
 */
public class UtilizatorDbRepository implements Repository<Long, Utilizator> {

    private final Validator<Utilizator> validator;
    private final String url;
    private final String username;
    private final String password;

    /**
     *
     * @param validator - the validation strategy for users
     * @param url       - the JDBC url of the database
     * @param username  - the database user
     * @param password  - the password of the database user
     */
    public UtilizatorDbRepository(Validator<Utilizator> validator, String url, String username, String password) {
        this.validator = validator;
        this.url = url;
        this.username = username;
        this.password = password;
    }

    // ---------------- Cerinta 2. findAll ----------------
    // Cititi toti utilizatorii din tabela users.
    //   - Connection, PreparedStatement si ResultSet se deschid in try-with-resources;
    //   - fiecare rand (while (resultSet.next())) devine un Utilizator;
    //   - SQLException se transforma in RepositoryException.

    /**
     *
     * @return all users, ordered by id
     * @throws RepositoryException if a database access error occurs
     */
    @Override
    public Iterable<Utilizator> findAll() {
        List<Utilizator> users = new ArrayList<>();
        try (Connection connection = DriverManager.getConnection(url, username, password);
             PreparedStatement statement = connection.prepareStatement("SELECT * FROM users ORDER BY id");
             ResultSet resultSet = statement.executeQuery()) {

            while (resultSet.next()) {
                Long id = resultSet.getLong("id");
                String firstName = resultSet.getString("first_name");
                String lastName = resultSet.getString("last_name");

                Utilizator utilizator = new Utilizator(firstName, lastName);
                utilizator.setId(id);
                users.add(utilizator);
            }
        } catch (SQLException e) {
            throw new RepositoryException("Eroare la findAll: " + e.getMessage(), e);
        }
        return users;
    }

    // ---------------- Cerinta 3. findOne ----------------
    // Cautati utilizatorul dupa id, cu WHERE id = ? (parametru, nu concatenare).
    // Intoarceti Optional.of(utilizator) sau Optional.empty() daca nu exista.

    /**
     *
     * @param id - the id of the user to be returned; must not be null
     * @return an Optional with the user with the specified id
     * or Optional.empty() - if there is no user with the given id
     * @throws IllegalArgumentException if id is null.
     * @throws RepositoryException      if a database access error occurs
     */
    @Override
    public Optional<Utilizator> findOne(Long id) {
        if (id == null)
            throw new IllegalArgumentException("id must be not null");
        try (Connection connection = DriverManager.getConnection(url, username, password);
             PreparedStatement statement = connection.prepareStatement("SELECT * FROM users WHERE id = ?")) {

            statement.setLong(1, id);
            try (ResultSet resultSet = statement.executeQuery()) {
                if (resultSet.next()) {
                    Utilizator utilizator = new Utilizator(resultSet.getString("first_name"),
                            resultSet.getString("last_name"));
                    utilizator.setId(id);
                    return Optional.of(utilizator);
                }
                return Optional.empty();
            }
        } catch (SQLException e) {
            throw new RepositoryException("Eroare la findOne: " + e.getMessage(), e);
        }
    }

    // ---------------- Cerinta 4. save ----------------
    // Validati utilizatorul, apoi INSERT doar cu first_name si last_name: id-ul il genereaza baza de date.
    // Cititi id-ul generat (getGeneratedKeys) si setati-l pe utilizator.

    /**
     * saves the user; the id is generated by the database and set on the entity
     *
     * @param entity - entity must be not null; its id is ignored
     * @return Optional.empty() - the entity is saved (with the generated id)
     * @throws curs.domain.validators.ValidationException if the entity is not valid
     * @throws IllegalArgumentException                   if the given entity is null.
     * @throws RepositoryException                        if a database access error occurs
     */
    @Override
    public Optional<Utilizator> save(Utilizator entity) {
        if (entity == null)
            throw new IllegalArgumentException("entity must be not null");
        validator.validate(entity);

        String sql = "INSERT INTO users (first_name, last_name) VALUES (?, ?)";
        try (Connection connection = DriverManager.getConnection(url, username, password);
             PreparedStatement ps = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {

            ps.setString(1, entity.getFirstName());
            ps.setString(2, entity.getLastName());
            ps.executeUpdate();

            try (ResultSet keys = ps.getGeneratedKeys()) {   // randul inserat, cu id-ul generat
                keys.next();
                entity.setId(keys.getLong("id"));
            }
        } catch (SQLException e) {
            throw new RepositoryException("Eroare la save: " + e.getMessage(), e);
        }
        return Optional.empty();
    }

    // ---------------- Cerinta 5. update ----------------
    // Validati utilizatorul, apoi UPDATE ... WHERE id = ?.
    // executeUpdate intoarce numarul de randuri modificate: 0 inseamna ca id-ul nu exista.

    /**
     *
     * @param entity - entity must not be null
     * @return Optional.empty() - if the entity is updated,
     * otherwise returns an Optional with the entity - (e.g id does not exist).
     * @throws IllegalArgumentException                   if the given entity is null.
     * @throws curs.domain.validators.ValidationException if the entity is not valid.
     * @throws RepositoryException                        if a database access error occurs
     */
    @Override
    public Optional<Utilizator> update(Utilizator entity) {
        if (entity == null)
            throw new IllegalArgumentException("entity must be not null!");
        validator.validate(entity);

        String sql = "UPDATE users SET first_name = ?, last_name = ? WHERE id = ?";
        try (Connection connection = DriverManager.getConnection(url, username, password);
             PreparedStatement ps = connection.prepareStatement(sql)) {

            ps.setString(1, entity.getFirstName());
            ps.setString(2, entity.getLastName());
            ps.setLong(3, entity.getId());
            int randuri = ps.executeUpdate();
            return randuri == 0 ? Optional.of(entity) : Optional.empty();
        } catch (SQLException e) {
            throw new RepositoryException("Eroare la update: " + e.getMessage(), e);
        }
    }

    // ---------------- Cerinta 6. delete ----------------
    // Stergeti utilizatorul cu id-ul dat si intoarceti-l (Optional);
    // daca nu exista, intoarceti Optional.empty(). Indiciu: intai findOne.

    /**
     *
     * @param id - id must be not null
     * @return an Optional with the removed user
     * or Optional.empty() - if there is no user with the given id
     * @throws IllegalArgumentException if the given id is null.
     * @throws RepositoryException      if a database access error occurs
     */
    @Override
    public Optional<Utilizator> delete(Long id) {
        Optional<Utilizator> gasit = findOne(id);
        if (gasit.isEmpty())
            return gasit;

        try (Connection connection = DriverManager.getConnection(url, username, password);
             PreparedStatement ps = connection.prepareStatement("DELETE FROM users WHERE id = ?")) {

            ps.setLong(1, id);
            ps.executeUpdate();
        } catch (SQLException e) {
            throw new RepositoryException("Eroare la delete: " + e.getMessage(), e);
        }
        return gasit;
    }
}
